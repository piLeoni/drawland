// library.d.ts: drawland.d.ts (the library as a profile sees it) as a module,
// so `Graph` can carry its namespaces without declaring them as globals in
// the project that installs the package. Run by `npm run build`.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const here = import.meta.dirname
const dts = readFileSync(join(here, '../../crates/drawland-script/drawland.d.ts'), 'utf8')
const names = ['features', 'areas', 'engine', 'page', 'world', 'lines', 'fills', 'burin', 'ink', 'modules', 'compose', 'draw', 'paint', 'output', 'title', 'view']
const face = `
/** The library, as a \`Graph\` built in Node carries it. */
export interface Library {
${names.map((n) => `  ${n}: typeof ${n}`).join('\n')}
}
`
writeFileSync(join(here, 'library.d.ts'), `// Generated by make-types.mjs from drawland.d.ts: do not edit.\n${dts}\n${face}`)
